"""Rebuild web/data.js from ../ie_data.xlsx (Shiller Data sheet).

Usage (from the invest_tops folder):
    python3 convert_data.py ~/Downloads/"ie_data (N).xls"   # .xls -> ie_data.xlsx
    python3 web/build_data.py                               # ie_data.xlsx -> web/data.js
then deploy:  cd web && vercel deploy --prod
"""
import json
from pathlib import Path

import openpyxl

HERE = Path(__file__).resolve().parent
XLSX = HERE.parent / "ie_data.xlsx"

wb = openpyxl.load_workbook(str(XLSX), data_only=True)
ws = wb["Data"]
rows = []
for row in ws.iter_rows(min_row=9, values_only=True):
    if row[0] is None:
        continue
    # columns A..K: date, price, div, earnings, CPI, date frac, GS10, real price, real div, real TR price, real earnings
    rows.append([v if isinstance(v, (int, float)) else None for v in row[:11]])

(HERE / "data.js").write_text(
    "// Generated by build_data.py from ie_data.xlsx. Do not edit by hand.\n"
    "window.SHILLER = " + json.dumps(rows, separators=(",", ":")) + ";\n"
)
print(f"wrote {len(rows)} rows, last date {rows[-1][0]}")
